CREATE TABLE [options].[ForecastRuns]
(
    [Id] INT IDENTITY(1,1) NOT NULL,
    [UserKey] NVARCHAR(200) NOT NULL,
    [RequestId] UNIQUEIDENTIFIER NOT NULL,
    [IndexCode] NVARCHAR(20) NOT NULL,
    [Mode] NVARCHAR(30) NOT NULL,
    [Status] NVARCHAR(30) NOT NULL CONSTRAINT [DF_Options_ForecastRuns_Status] DEFAULT (N'queued'),
    [JobRunId] INT NULL,
    [SnapshotBatchId] INT NULL,
    [GeneratedAt] DATETIME2 NOT NULL CONSTRAINT [DF_Options_ForecastRuns_GeneratedAt] DEFAULT (SYSUTCDATETIME()),
    [TargetAt] DATETIME2 NULL,
    [InputCutoffAt] DATETIME2 NULL,
    [ModelVersion] NVARCHAR(50) NOT NULL,
    [InputHash] NVARCHAR(64) NULL,
    [AnalysisJson] NVARCHAR(MAX) NULL,
    [ErrorMessage] NVARCHAR(2000) NULL,
    CONSTRAINT [PK_Options_ForecastRuns] PRIMARY KEY CLUSTERED ([Id]),
    CONSTRAINT [UQ_Options_ForecastRuns_Request] UNIQUE ([UserKey], [RequestId]),
    CONSTRAINT [FK_Options_ForecastRuns_MarketIndices] FOREIGN KEY ([IndexCode]) REFERENCES [options].[MarketIndices] ([Code]),
    CONSTRAINT [FK_Options_ForecastRuns_JobRuns] FOREIGN KEY ([JobRunId]) REFERENCES [dbo].[JobRuns] ([Id]),
    CONSTRAINT [FK_Options_ForecastRuns_MarketSnapshotBatches] FOREIGN KEY ([SnapshotBatchId]) REFERENCES [options].[MarketSnapshotBatches] ([Id]),
    CONSTRAINT [CK_Options_ForecastRuns_Mode] CHECK ([Mode] IN (N'daily', N'weekly', N'monthly', N'expiry-intraday')),
    CONSTRAINT [CK_Options_ForecastRuns_Status] CHECK ([Status] IN (N'queued', N'running', N'completed', N'failed', N'cancelled', N'unavailable')),
    CONSTRAINT [CK_Options_ForecastRuns_AnalysisJson] CHECK ([AnalysisJson] IS NULL OR ISJSON([AnalysisJson]) = 1),
    INDEX [IX_Options_ForecastRuns_History] NONCLUSTERED ([UserKey], [IndexCode], [Mode], [GeneratedAt] DESC),
    INDEX [IX_Options_ForecastRuns_Reconciliation] NONCLUSTERED ([Status], [TargetAt]),
    INDEX [IX_Options_ForecastRuns_JobRunId] NONCLUSTERED ([JobRunId]),
    INDEX [IX_Options_ForecastRuns_SnapshotBatchId] NONCLUSTERED ([SnapshotBatchId])
);
