CREATE TABLE [dbo].[IndianStage4AnalysisResults]
(
    [Id] INT IDENTITY(1,1) NOT NULL,
    [RunId] INT NOT NULL,
    [WeekNumber] NVARCHAR(10) NOT NULL,
    [Symbol] NVARCHAR(50) NOT NULL,
    [CompanyName] NVARCHAR(500) NOT NULL,
    [SectorId] INT NOT NULL,
    [SectorName] NVARCHAR(200) NOT NULL,
    [ClosePrice] DECIMAL(18,4) NULL,
    [MA10] DECIMAL(18,4) NULL,
    [MA30] DECIMAL(18,4) NULL,
    [MA30FourWeeksAgo] DECIMAL(18,4) NULL,
    [MarketCap] DECIMAL(22,2) NULL,
    [IsStage4] BIT NULL,
    [AnalysisStatus] NVARCHAR(20) NOT NULL,
    [ErrorMessage] NVARCHAR(MAX) NULL,
    [PriceAsOfDate] DATE NULL,
    [EligibilityCapturedAt] DATETIME2 NOT NULL,
    [Classification] NVARCHAR(20) NULL,
    [WeeksInStage4] INT NULL,
    [RSScore] DECIMAL(20,8) NULL,
    [RSDelta1w] DECIMAL(20,8) NULL,
    [RSDelta2w] DECIMAL(20,8) NULL,
    [RSDelta3w] DECIMAL(20,8) NULL,
    [MomentumScore] DECIMAL(20,8) NULL,
    [ROC1w] DECIMAL(20,8) NULL,
    [ROC2w] DECIMAL(20,8) NULL,
    [ROC3w] DECIMAL(20,8) NULL,
    [Quadrant] NVARCHAR(20) NULL,
    [ADRatio] DECIMAL(20,8) NULL,
    [ADClassification] NVARCHAR(20) NULL,
    [CreatedAt] DATETIME2 NOT NULL DEFAULT GETUTCDATE(),

    CONSTRAINT [PK_IndianStage4AnalysisResults] PRIMARY KEY CLUSTERED ([Id]),
    CONSTRAINT [FK_IndianStage4AnalysisResults_JobRuns] FOREIGN KEY ([RunId]) REFERENCES [dbo].[JobRuns]([Id]),
    CONSTRAINT [UX_IndianStage4AnalysisResults_RunSymbol] UNIQUE NONCLUSTERED ([RunId], [Symbol]),
    CONSTRAINT [CK_IndianStage4AnalysisResults_Status] CHECK ([AnalysisStatus] IN ('evaluated', 'insufficient', 'stale', 'error')),
    CONSTRAINT [CK_IndianStage4AnalysisResults_Evaluated] CHECK
        (([AnalysisStatus] = 'evaluated' AND [IsStage4] IS NOT NULL) OR ([AnalysisStatus] <> 'evaluated' AND [IsStage4] IS NULL)),
    CONSTRAINT [CK_IndianStage4AnalysisResults_Classification] CHECK ([Classification] IN ('new', 'reentry', 'continuing', 'removed')),
    CONSTRAINT [CK_IndianStage4AnalysisResults_Quadrant] CHECK ([Quadrant] IN ('leading', 'weakening', 'lagging', 'improving')),
    CONSTRAINT [CK_IndianStage4AnalysisResults_ADClassification] CHECK ([ADClassification] IN ('accumulating', 'distributing', 'neutral')),
    INDEX [IX_IndianStage4AnalysisResults_Week] NONCLUSTERED ([WeekNumber], [RunId]),
    INDEX [IX_IndianStage4AnalysisResults_Run_Stage4] NONCLUSTERED ([RunId], [IsStage4])
        INCLUDE ([SectorId], [RSScore], [MomentumScore], [Classification])
);
